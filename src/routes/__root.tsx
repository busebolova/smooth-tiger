function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="tr">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <StoreProvider>
        <MotionDirector />
        <Header />
        <Outlet />
        <Footer />
        <CartDrawer />
        <AccountPanel />
      </StoreProvider>
    </QueryClientProvider>
  );
}
